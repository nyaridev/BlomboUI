/**
 * One source of truth for AI rules: `.claude/rules/*.md` (Claude Code, `paths:` frontmatter) are
 * converted into `.cursor/rules/*.mdc` (Cursor, `globs:` frontmatter), plus one always-on project
 * rule that points Cursor at AGENTS.md.
 *
 *   npm run rules:sync                 regenerate .cursor/rules
 *   node tools/sync-rules.ts --check   fail if .cursor/rules is out of date (used by npm run check)
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const root = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
const source = path.join(root, ".claude", "rules");
const target = path.join(root, ".cursor", "rules");
const check = process.argv.includes("--check");

const PROJECT_RULE = `---
description: BlomboUI project guide (read AGENTS.md first)
alwaysApply: true
---
<!-- Generated by \`npm run rules:sync\`. Edit .claude/rules/ or AGENTS.md instead. -->

Follow @AGENTS.md (architecture, commands, golden rules, workflows). Details: @docs/architecture.md, @docs/design-system.md and @docs/workflows.md.

Essentials: ComfyUI is the engine, Blombo binds and patches real graphs · one Zod schema per shape in src/shared · workflows and layouts are data · tokens + src/client/ui components only, new controls go in the Design Lab · user data is written only through src/server/lib/fsx.ts · server/shared/tools use relative \`.ts\` imports and erasable TypeScript · finish with \`npm run check\`.
`;

function render(name: string, text: string): string {
  const match = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/.exec(text);
  const meta = (match ? parse(match[1] ?? "") : {}) as { description?: string; paths?: string[] };
  const body = (match ? (match[2] ?? "") : text).trim();
  const globs = meta.paths?.length ? meta.paths.join(",") : null;
  return [
    "---",
    `description: ${meta.description ?? name}`,
    ...(globs ? [`globs: ${globs}`] : []),
    `alwaysApply: ${globs ? "false" : "true"}`,
    "---",
    `<!-- Generated from .claude/rules/${name}.md by \`npm run rules:sync\`. Edit the source, not this file. -->`,
    "",
    body,
    "",
  ].join("\n");
}

const expected = new Map<string, string>([["blombo.mdc", PROJECT_RULE]]);
for (const file of fs
  .readdirSync(source)
  .filter((f) => f.endsWith(".md"))
  .sort()) {
  const name = file.replace(/\.md$/, "");
  expected.set(`${name}.mdc`, render(name, fs.readFileSync(path.join(source, file), "utf8")));
}

const existing = fs.existsSync(target)
  ? fs.readdirSync(target).filter((f) => f.endsWith(".mdc"))
  : [];
const stale = [
  ...[...expected]
    .filter(([file, content]) => {
      const p = path.join(target, file);
      return (fs.existsSync(p) ? fs.readFileSync(p, "utf8") : null) !== content;
    })
    .map(([file]) => file),
  ...existing.filter((file) => !expected.has(file)),
];

if (check) {
  if (stale.length) {
    console.error(`✖ .cursor/rules is out of date (${stale.join(", ")}). Run: npm run rules:sync`);
    process.exit(1);
  }
  console.log("✔ .cursor/rules is in sync with .claude/rules");
  process.exit(0);
}

fs.mkdirSync(target, { recursive: true });
for (const file of existing) if (!expected.has(file)) fs.rmSync(path.join(target, file));
for (const [file, content] of expected) fs.writeFileSync(path.join(target, file), content);
console.log(`✔ Wrote ${expected.size} Cursor rules to .cursor/rules/`);
